def nonces_csv():
    # Unhashed 24-byte nonces, as older Android databases may still hold them.
    return row("nonces") + row("00" * 24) + row("11" * 24)


def nonces_d2d_csv():
    # Hashed: HMAC-SHA256(key "ABCD1234", 0x22 * 24); then one cell that is neither form.
    return (
        row("nonces")
        + row("e41a9436d4615f05e2b8efc1fb80002c25d16ce18983505cdf49af653e894d71")
        + row("zz")
    )


def main():
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, "android-backup.zip")
    with pyzipper.AESZipFile(
        path, "w", compression=pyzipper.ZIP_DEFLATED, encryption=pyzipper.WZ_AES
    ) as archive:
        archive.setpassword(PASSWORD)

        def add(name, data, stored=False, zip64=False):
            if isinstance(data, str):
                data = data.encode("utf-8")
            info = archive.zipinfo_cls(name)
            info.compress_type = pyzipper.ZIP_STORED if stored else pyzipper.ZIP_DEFLATED
            with archive.open(info, "w", force_zip64=zip64) as entry:
                entry.write(data)

        add("settings", row("version", "27"))
        add("identity", IDENTITY_BACKUP, stored=True)
        add("contacts.csv", contacts_csv())
        add("groups.csv", groups_csv())
        add("distribution_list.csv", lists_csv())
        add("message_17.csv", messages_csv())
        add("group_message_g-17.csv", group_messages_csv())
        add("ballot.csv", ballot_csv())
        add("ballot_choice.csv", ballot_choice_csv())
        add("ballot_vote.csv", ballot_vote_csv())
        add("contact_reactions.csv", contact_reactions_csv())
        add("group_reactions.csv", group_reactions_csv())
        # Media bytes are opaque here; big enough that a flipped ciphertext byte lands in them.
        add("message_media_m-0002", bytes(range(256)) * 8, stored=True)
        add("message_thumbnail_m-0002", b"\xff\xd8" + b"\x00" * 64, stored=True)
        add("message_media_m-0008", bytes(range(256)) * 8, stored=True)
        add("contact_avatar_me", b"\xff\xd8" + b"\x01" * 64, stored=True)
        add("contact_avatar_17", b"\xff\xd8" + b"\x02" * 64, stored=True)
        add("contact_profile_pic_17", b"\xff\xd8" + b"\x03" * 64, stored=True)
        add("group_avatar_g-17", b"\xff\xd8" + b"\x04" * 64, stored=True)
        add("nonces.csv", nonces_csv(), zip64=True)
        add("nonces_d2d.csv", nonces_d2d_csv())
        add("nonce_counts.csv", row("csp", "d2d") + row("2", "2"))
        add("future_stuff.csv", row("something", "new"))
    print(path)

    path = os.path.join(OUT, "android-backup-unicode.zip")
    with pyzipper.AESZipFile(
        path, "w", compression=pyzipper.ZIP_DEFLATED, encryption=pyzipper.WZ_AES
    ) as archive:
        archive.setpassword(UNICODE_PASSWORD)
        archive.writestr("settings", row("version", "27").encode("utf-8"))
    print(path)


if __name__ == "__main__":
    main()
