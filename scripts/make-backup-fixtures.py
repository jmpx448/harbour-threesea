"""Build the synthetic Android-backup fixtures (core/tests/fixtures/android-backup*.zip).

Android writes its data backup with Zip4j: every entry AES-256 (WinZip AE), DEFLATE at level
normal or "no compression" (FileHandlingZipOutputStream.kt). pyzipper is an independent
implementation of the same WinZip AES format, so these fixtures prove our reader against
something that is not itself. Content is entirely synthetic (CLAUDE.md: no personal data);
the identity entry is an encrypted ID backup for the made-up ID ABCD1234 with client key
0x07*32, password "test-password" (generated by the ignored test
android_backup::tests::generate_identity_backup_string).

Run (needs pyzipper, e.g. in a venv: pip install pyzipper):
    python3 scripts/make-backup-fixtures.py
The fixtures are committed; rerun only when the layout must change.
"""

