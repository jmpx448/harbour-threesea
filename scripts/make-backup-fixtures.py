def field(value):
    """CSVRow.escape + opencsv CSVWriter: backslashes doubled, every field quoted, quotes
    doubled."""
    return '"' + value.replace("\\", "\\\\").replace('"', '""') + '"'


def row(*values):
    return ",".join(field(v) for v in values) + "\n"


