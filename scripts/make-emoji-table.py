"""Generate qml/components/EmojiTable.js and copy the Twemoji sprite sheets (Threema Libre's,
CC-BY 4.0) from the upstream submodule into emojis/.

Android maps every emoji (a codepoint sequence, with and without variation selectors) to a
64x64 cell of a sprite sheet in its generated EmojiParser.kt; we reuse that mapping so the same
sequences show the same pictures. Run again after updating the submodule.
"""
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UPSTREAM = ROOT / "third_party/threema-android/app/src"
PARSER = UPSTREAM / "main/java/ch/threema/app/emojis/EmojiParser.kt"
SHEETS = UPSTREAM / "foss_based/assets/emojis"
# EmojiManager.emojiGroups: index 0 is "recent".
GROUPS = [None, "smileys", "people", "nature", "food", "activity", "travel", "objects", "symbols", "flags"]

entry = re.compile(r"trie\.insert\(intArrayOf\(([0-9, ]+)\), ParseResult\(\d+, "
                   r"SpriteCoordinates\((\d+), (\d+), (\d+), (\d+)\)\)\)")
table = {}
for match in entry.finditer(PARSER.read_text()):
    codepoints = [int(c) for c in match.group(1).split(",")]
    group, sheet, x, y = (int(v) for v in match.groups()[1:])
    key = "-".join(format(c, "x") for c in codepoints)
    table[key] = f"{GROUPS[group]}-{sheet},{x},{y}"
if len(table) < 4000:
    sys.exit(f"only {len(table)} emoji found: EmojiParser.kt changed?")
longest = max(len(k.split("-")) for k in table)
# Every start of a longer sequence, so that a scan stops as soon as no emoji can come of it:
# "" for those that aren't emoji themselves.
lookup = dict(table)
for key in table:
    parts = key.split("-")
    for n in range(1, len(parts)):
        lookup.setdefault("-".join(parts[:n]), "")


def spans(codepoints, gap):
    """The codepoints as a JS test on `c`, in ranges bridging gaps of at most `gap`."""
    ranges = []
    for c in sorted(codepoints):
        if ranges and c - ranges[-1][1] <= gap:
            ranges[-1][1] = c
        else:
            ranges.append([c, c])
    return " || ".join(f"c === {a:#x}" if a == b else f"(c >= {a:#x} && c <= {b:#x})" for a, b in ranges)


firsts = {int(key.split("-")[0], 16) for key in table}
# Below this come the letters of nearly every text: only exact ranges. Above it, the emoji's
# blocks are enough to pass over other scripts without building a key for each character.
ASCII_END = 0x80

# The tables are JSON in one string, parsed at first use: a string costs next to nothing when the
# script loads at start, an object literal is built right there, with the emoji or without them.
out = ROOT / "qml/components/EmojiTable.js"
out.write_text(
    "// SPDX-License-Identifier: AGPL-3.0-only\n"
    "// Generated by scripts/make-emoji-table.py from Threema Android's EmojiParser.kt: codepoints\n"
    "// (hex, joined by '-') -> 'sheet,x,y' of a 64x64 cell in emojis/<sheet>.png (Twemoji), or \"\"\n"
    "// for the start of a longer sequence that is no emoji itself.\n"
    ".pragma library\n\n"
    f"var data = {json.dumps(json.dumps(lookup, separators=(',', ':'), sort_keys=True))}\n"
    "var parsed = null\n\n"
    "function table() {\n"
    "    if (!parsed) {\n"
    "        parsed = JSON.parse(data)\n"
    "        data = \"\"\n"
    "    }\n"
    "    return parsed\n"
    "}\n\n"
    "// Whether an emoji can start with this codepoint (no table needed to say no).\n"
    "function mayStart(c) {\n"
    f"    if (c < {ASCII_END:#x}) return {spans({f for f in firsts if f < ASCII_END}, 1)}\n"
    f"    return {spans({f for f in firsts if f >= ASCII_END}, 16)}\n"
    "}\n")

# The picker's list (Android's EmojiSpritemap.kt): per category, the shown emoji in Threema's
# order, each with its skin tone variants.
SPRITEMAP = UPSTREAM / "main/java/ch/threema/app/emojis/EmojiSpritemap.kt"
info = re.compile(r'EmojiInfo\(\s*"([^"]+)",\s*(DIVERSITY_\w+),\s*(null|arrayOf\(([^)]*)\)),\s*(DISPLAY_\w+),')


def decode(kotlin):
    return json.loads('"' + kotlin + '"')


def cell_of(sequence):
    return table.get("-".join(format(ord(c), "x") for c in sequence))


spritemap = SPRITEMAP.read_text()
categories = []
for match in re.finditer(r"private fun get(\w+)\(\) = listOf\(", spritemap):
    start = match.end()
    end = spritemap.find("private fun get", start)
    body = spritemap[start:end if end > 0 else len(spritemap)]
    shown = {}
    entries = []
    for m in info.finditer(body):
        sequence = decode(m.group(1))
        shown[sequence] = m.group(5) == "DISPLAY_YES"
        entries.append((sequence, m.group(2), m.group(4)))
    items = []
    for sequence, diversity, variants in entries:
        if diversity == "DIVERSITY_CHILD" or not shown[sequence] or not cell_of(sequence):
            continue
        item = [sequence, cell_of(sequence)]
        if variants:
            tones = [decode(v) for v in re.findall(r'"([^"]+)"', variants)]
            tones = [[t, cell_of(t)] for t in tones if shown.get(t, True) and cell_of(t)]
            if tones:
                item.append(tones)
        items.append(item)
    categories.append([match.group(1), items])
# In the order of Android's picker (emojiCategories), not of the file's functions.
categories.sort(key=lambda c: GROUPS.index(c[0]))
if sum(len(items) for _, items in categories) < 1500:
    sys.exit("too few emoji in EmojiSpritemap.kt: changed?")
picker = json.dumps([items for _, items in categories], ensure_ascii=False, separators=(",", ":"))
(ROOT / "qml/components/EmojiPickerData.js").write_text(
    "// SPDX-License-Identifier: AGPL-3.0-only\n"
    "// Generated by scripts/make-emoji-table.py from Threema Android's EmojiSpritemap.kt: the\n"
    "// picker's categories in Threema's order, each emoji [text, cell, [[skin tone text, cell]]].\n"
    "// Parsed the first time the picker opens, see EmojiTable.js.\n"
    ".pragma library\n\n"
    f"var names = {json.dumps([name for name, _ in categories], separators=(',', ':'))}\n"
    f"var data = {json.dumps(picker, ensure_ascii=False)}\n"
    "var parsed = null\n\n"
    "function items(category) {\n"
    "    if (!parsed) {\n"
    "        parsed = JSON.parse(data)\n"
    "        data = \"\"\n"
    "    }\n"
    "    return parsed[category]\n"
    "}\n")

target = ROOT / "emojis"
target.mkdir(exist_ok=True)
for png in sorted(SHEETS.glob("*.png")):
    shutil.copyfile(png, target / png.name)
print(f"{len(table)} emoji, longest {longest} codepoints, {len(list(target.glob('*.png')))} sheets")
